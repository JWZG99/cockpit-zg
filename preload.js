// Bridge between the page and the desktop side; the page builds window.claude on top of it (app/claude-shim.js)
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('native', {
  dbAll: () => ipcRenderer.invoke('db-all'),
  dbWrite: (ops) => ipcRenderer.invoke('db-write', ops),
  onDbChanged: (cb) => ipcRenderer.on('db-changed', (_e, store) => cb(store)),
  assetPut: (bytes, name, type) => ipcRenderer.invoke('asset-put', { bytes, name, type }),
  assetDelete: (id) => ipcRenderer.invoke('asset-delete', id),
  saveFile: (filename, bytes) => ipcRenderer.invoke('save-file', { filename, bytes }),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  pickPath: (kind) => ipcRenderer.invoke('pick-path', kind),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  makeDir: (inDir, name) => ipcRenderer.invoke('make-dir', { in: inDir, name }),
  deletePath: (p) => ipcRenderer.invoke('delete-path', p),
  movePath: (von, nach, kopie) => ipcRenderer.invoke('move-path', { von, nach, kopie: !!kopie }),
  dataDir: () => ipcRenderer.invoke('data-dir'),
  chooseDataDir: () => ipcRenderer.invoke('choose-data-dir'),
  dataStatus: () => ipcRenderer.invoke('data-status'),
  onDataStatus: (cb) => ipcRenderer.on('data-status', (_e, st) => cb(st)),
  pathOf: (file) => { try { return webUtils.getPathForFile(file) || ''; } catch (_) { return ''; } },
  listDir: (p) => ipcRenderer.invoke('list-dir', p),
  searchDir: (o) => ipcRenderer.invoke('search-dir', o),
  searchCancel: () => ipcRenderer.invoke('search-cancel'),
  searchForget: () => ipcRenderer.invoke('search-forget'),
  onSearchProgress: (cb) => ipcRenderer.on('search-progress', (_e, d) => cb(d)),
  pfadInfo: (liste) => ipcRenderer.invoke('pfad-info', liste),
  authState: () => ipcRenderer.invoke('auth-state'),
  authSetup: (d) => ipcRenderer.invoke('auth-setup', d),
  authLogin: (id, pw) => ipcRenderer.invoke('auth-login', { id, pw }),
  authRegister: (d) => ipcRenderer.invoke('auth-register', d),
  aktivitaet: () => ipcRenderer.invoke('aktivitaet'),
  onAktivitaet: (cb) => ipcRenderer.on('aktivitaet', (_e, a) => cb(a)),
  updateBereit: () => ipcRenderer.invoke('update-bereit'),
  onUpdateBereit: (cb) => ipcRenderer.on('update-bereit', (_e, v) => cb(v)),
  bautenAbgleichen: () => ipcRenderer.invoke('bauten-abgleichen'),
  neuLaden: () => ipcRenderer.invoke('neu-laden'),
  neuStarten: () => ipcRenderer.invoke('neu-starten'),
  onNeueVersionLokal: (cb) => ipcRenderer.on('neue-version-lokal', () => cb()),
  version: () => ipcRenderer.invoke('version'),
  mailListe: (o) => ipcRenderer.invoke('mail-liste', o),
  mailDetail: (id) => ipcRenderer.invoke('mail-detail', id),
  mailOeffnen: (id) => ipcRenderer.invoke('mail-oeffnen', id),
  mailAntworten: (id, alle) => ipcRenderer.invoke('mail-antworten', { id, alle: !!alle }),
  mailNeu: (o) => ipcRenderer.invoke('mail-neu', o),
  updateInstallieren: () => ipcRenderer.invoke('update-installieren'),
  authLogout: () => ipcRenderer.invoke('auth-logout'),
  me: () => ipcRenderer.invoke('auth-me'),
  changePassword: (alt, neu) => ipcRenderer.invoke('auth-password', { alt, neu }),
  teamList: () => ipcRenderer.invoke('team-list'),
  teamSave: (d) => ipcRenderer.invoke('team-save', d),
  kiStatus: () => ipcRenderer.invoke('ki-status'),
  kiSchluessel: (k) => ipcRenderer.invoke('ki-schluessel', k),
  kiFrage: (t) => ipcRenderer.invoke('ki-frage', t),
  kiModus: (m) => ipcRenderer.invoke('ki-modus', m),
  kiNeu: () => ipcRenderer.invoke('ki-neu'),
  onKiSchritt: (cb) => ipcRenderer.on('ki-schritt', (_e, n) => cb(n)),
  onAskDataDir: (cb) => ipcRenderer.on('ask-data-dir', () => cb()),
});
